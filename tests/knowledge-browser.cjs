'use strict';
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const base = process.env.WB_KNOWLEDGE_BASE_URL || 'http://127.0.0.1:8765';
if (process.env.WORKFLOWBUILDER_ALLOW_NATIVE_TESTS !== '1' || !['localhost','127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Dedicated local GLPI required');
(async () => {
    const browser = await chromium.launch({headless:true});
    const context = await browser.newContext({viewport:{width:1440,height:1000},locale:'fr-FR'});
    const page = await context.newPage();
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    page.on('dialog', d => d.accept());
    try {
        await page.goto(base + '/index.php?noAUTO=1');
        await page.locator('input[type="text"]').first().fill(process.env.WB_GLPI_TEST_USER || 'glpi');
        await page.locator('input[type="password"]').fill(process.env.WB_GLPI_TEST_PASSWORD || 'glpi');
        await Promise.all([page.waitForURL(url => !url.pathname.endsWith('/index.php')), page.locator('button[type="submit"]').first().click()]);
        await page.goto(base + '/plugins/workflowbuilder/front/template.form.php');
        const title = 'Recette connaissances ' + Date.now();
        await page.getByLabel('Nom',{exact:true}).fill(title);
        await page.getByRole('button',{name:'Étapes',exact:true}).click();
        await page.getByRole('button',{name:'Ajouter une étape',exact:true}).click();
        const step = page.locator('.wb-step-editor').first();
        await step.getByLabel('Titre',{exact:true}).fill('Contrôler le réseau');
        assert.equal(await step.getByLabel('Instructions',{exact:true}).count(),0);
        await step.getByRole('button',{name:'Créer une fiche',exact:true}).click();
        const createResponse = page.waitForResponse(r => r.url().endsWith('/front/knowledge.php') && r.request().method() === 'POST');
        await step.getByRole('button',{name:'Créer et associer la fiche',exact:true}).click();
        const response = await createResponse;
        assert.equal(response.status(),201,await response.text());
        const item = (await response.json()).item;
        await step.getByRole('link',{name:'Compléter la fiche dans GLPI',exact:true}).waitFor();
        console.log('PASS create and associate a structured procedure through the native endpoint');
        const tokenReject = await context.request.post(base + '/plugins/workflowbuilder/front/knowledge.php',{form:{title:'Rejected'}});
        assert.equal(tokenReject.status(),403);
        assert.match((await tokenReject.json()).error,/expiré/);
        console.log('PASS HTTP creation rejects an absent CSRF token');
        const popupPromise = page.waitForEvent('popup');
        await step.getByRole('link',{name:'Compléter la fiche dans GLPI',exact:true}).click();
        const popup = await popupPromise; await popup.waitForLoadState('domcontentloaded');
        assert.equal(new URL(popup.url()).searchParams.get('id'),String(item.id));
        await popup.close();
        console.log('PASS GLPI article opens in another tab');
        await step.getByRole('button',{name:'Choisir une fiche',exact:true}).click();
        await step.getByLabel('Rechercher des fiches',{exact:true}).fill(title);
        await step.getByRole('button',{name:'Déjà associée',exact:true}).waitFor();
        assert.match(await step.locator('.wb-knowledge-results').textContent(),/Prérequis/);
        console.log('PASS native search shows the persisted article and its text excerpt');
        await page.getByRole('button',{name:'Enregistrer le brouillon',exact:true}).click();
        await page.getByText('Brouillon enregistré.',{exact:false}).waitFor();
        const templateId = new URL(page.url()).searchParams.get('id');
        assert.ok(Number(templateId) > 0);
        await page.getByRole('button',{name:'Étapes',exact:true}).click();
        const saved = page.locator('.wb-step-editor').first();
        await saved.locator('summary').first().click();
        await saved.locator('.wb-knowledge-selected a').waitFor();
        assert.equal(await saved.locator('.wb-knowledge-selected a').textContent(),title + ' — Contrôler le réseau');
        console.log('PASS saved workflow reloads linked article titles');
        if (process.env.WB_KNOWLEDGE_PREVIEW_PATH) await saved.locator('.wb-knowledge').screenshot({path:process.env.WB_KNOWLEDGE_PREVIEW_PATH});
        await page.getByRole('button',{name:'Publier une nouvelle version',exact:true}).click();
        await page.goto(base + '/plugins/workflowbuilder/front/launch.php?template=' + templateId);
        await page.getByRole('button',{name:'Valider et créer le ticket',exact:true}).click();
        await page.locator('.wb-procedures a').waitFor();
        assert.equal(new URL(await page.locator('.wb-procedures a').getAttribute('href'),base).searchParams.get('id'),String(item.id));
        assert.equal(await page.locator('.wb-instructions').count(),0);
        console.log('PASS published ticket step links directly to the selected native article');
        await page.setViewportSize({width:390,height:844});
        await page.evaluate(() => document.fonts.ready);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
        assert.deepEqual(errors,[]);
        console.log('PASS native ticket view fits mobile and has no JavaScript errors');
    } finally { await context.close(); await browser.close(); }
})().catch(error => {console.error(error);process.exitCode=1;});
